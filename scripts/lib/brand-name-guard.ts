// Story 72.16 (CM request R1): the product name is read from ONE message key, `brand_name`, so a host
// renames PV everywhere by overlaying that key. This is the scanner behind `check-brand-name`: it
// fails on any user-visible occurrence of the product name in apps/web outside that key.
//
// What is read, and how (never a regex over source text, so comments and code are told apart):
//   - `.svelte`  -> `svelte/compiler`'s modern AST: markup text, attribute values and every string or
//     template literal of the script. Comments are not nodes, so a comment may name the product.
//   - `.ts`      -> TypeScript's compiler API: string, no-substitution-template and template parts.
//   - `.html`    -> HTML comments removed, the rest read as text (`src/app.html`).
//   - `messages/<locale>.json` -> every value except the one for `brand_name` (a message that names
//     the product takes it as the `{brand}` parameter instead).
// Test files (`*.test.ts`, `*.spec.ts`) are not product copy and are not scanned; they read the
// message function (story 72.19 pins the same rule for the overlay tests).
//
// Nothing else is excused: the only place the literal may live is the `brand_name` value itself.
import { join, posix } from 'node:path'
import ts from 'typescript'
import { readText, listNames, statPath } from './fs-access.js'
import { svelteCompiler } from './route-files.js'
import { toRepoPath, walkFiles } from './scan-utils.js'

export const BRAND_LITERAL = 'Project Vault'
export const BRAND_MESSAGE_KEY = 'brand_name'
const SCANNED_DIRS = ['src']
const SCANNED_FILE = /\.(svelte|ts|js|html)$/
/** The name in any case, with any run of whitespace (incl. a line break or NBSP) between the words. */
const BRAND_PATTERN = /project[\s\u00a0]+vault/i
const TEST_FILE = /\.(test|spec)\.[cm]?[jt]s$/
/** Generated by `paraglide:compile` (gitignored); never product source. */
const GENERATED_DIR = 'src/lib/paraglide'

export interface BrandNameResult {
  files: number
  messageFiles: number
  problems: string[]
}

function namesProduct(text: string | null): boolean {
  return text !== null && BRAND_PATTERN.test(text)
}

function lineOf(source: string, offset: number): number {
  return source.slice(0, offset).split('\n').length
}

/** Line of every string or template part that names the product, in a .ts file. */
function tsHits(source: string): number[] {
  const file = ts.createSourceFile('x.ts', source, ts.ScriptTarget.Latest, true)
  const lines: number[] = []
  const visit = (node: ts.Node): void => {
    const text = literalText(node)
    if (namesProduct(text)) {
      lines.push(file.getLineAndCharacterOfPosition(node.getStart(file)).line + 1)
    }
    ts.forEachChild(node, visit)
  }
  visit(file)
  return lines
}

function literalText(node: ts.Node): string | null {
  if (
    ts.isStringLiteral(node) ||
    ts.isNoSubstitutionTemplateLiteral(node) ||
    ts.isTemplateHead(node) ||
    ts.isTemplateMiddle(node) ||
    ts.isTemplateTail(node)
  ) {
    return node.text
  }
  return null
}

/** Offset of every markup text, attribute value and script literal that names the product. */
function svelteHits(source: string): number[] {
  const root = svelteCompiler.parse(source, { modern: true }) as unknown
  const offsets: number[] = []
  const visit = (value: unknown): void => {
    if (Array.isArray(value)) {
      for (const item of value) visit(item)
    } else if (value !== null && typeof value === 'object') {
      visitNode(value as Record<string, unknown>, offsets, visit)
    }
  }
  visit(root)
  return offsets
}

function visitNode(
  node: Record<string, unknown>,
  offsets: number[],
  visit: (value: unknown) => void
): void {
  const text = svelteNodeText(node)
  if (namesProduct(text) && typeof node.start === 'number') offsets.push(node.start)
  for (const [key, child] of Object.entries(node)) {
    if (key !== 'metadata' && typeof child === 'object') visit(child)
  }
}

function svelteNodeText(node: Record<string, unknown>): string | null {
  if (node.type === 'Text' && typeof node.data === 'string') return node.data
  if (node.type === 'Literal' && typeof node.value === 'string') return node.value
  if (node.type === 'TemplateElement') {
    const cooked = (node.value as { cooked?: string | null } | undefined)?.cooked
    return typeof cooked === 'string' ? cooked : null
  }
  return null
}

function htmlHits(source: string): number[] {
  const stripped = source.replaceAll(/<!--[\s\S]*?-->/g, (comment) =>
    comment.replaceAll(/[^\n]/g, ' ')
  )
  const offsets: number[] = []
  for (const match of stripped.matchAll(new RegExp(BRAND_PATTERN, 'gi'))) offsets.push(match.index)
  return offsets
}

function hitLines(extension: string, source: string): number[] {
  if (extension === '.ts') return tsHits(source)
  const offsets = extension === '.svelte' ? svelteHits(source) : htmlHits(source)
  return offsets.map((offset) => lineOf(source, offset))
}

function messageProblems(rel: string, source: string): string[] {
  let catalogue: unknown
  try {
    catalogue = JSON.parse(source)
  } catch {
    return [`${rel}: not valid JSON`]
  }
  if (catalogue === null || typeof catalogue !== 'object')
    return [`${rel}: not a message catalogue`]
  const problems: string[] = []
  const entries = Object.entries(catalogue as Record<string, unknown>)
  if (!entries.some(([key]) => key === BRAND_MESSAGE_KEY)) {
    problems.push(`${rel}: the "${BRAND_MESSAGE_KEY}" message is missing`)
  }
  for (const [key, value] of entries) {
    if (key === BRAND_MESSAGE_KEY || typeof value !== 'string') continue
    if (BRAND_PATTERN.test(value)) {
      problems.push(
        `${rel}: message "${key}" hard-codes "${BRAND_LITERAL}"; take it as the {brand} parameter`
      )
    }
  }
  return problems
}

export function checkBrandNameGuard(webRoot: string): BrandNameResult {
  const problems: string[] = []
  let files = 0
  for (const dir of SCANNED_DIRS) {
    const base = join(webRoot, dir)
    for (const file of walkFiles(base, (path) => SCANNED_FILE.test(path))) {
      const rel = toRepoPath(webRoot, file)
      if (TEST_FILE.test(rel) || rel.startsWith(`${GENERATED_DIR}/`)) continue
      files += 1
      const source = readText(file)
      let lines: number[]
      try {
        lines = hitLines(posix.extname(rel), source)
      } catch (error) {
        problems.push(`${rel}: cannot be parsed (${(error as Error).message})`)
        continue
      }
      for (const line of lines) {
        problems.push(
          `${rel}:${line}: hard-codes "${BRAND_LITERAL}"; read m.${BRAND_MESSAGE_KEY}()`
        )
      }
    }
  }
  const messagesDir = join(webRoot, 'messages')
  const catalogues = listNames(messagesDir)
    .filter((name) => name.endsWith('.json') && statPath(join(messagesDir, name)).isFile())
    .sort((a, b) => a.localeCompare(b))
  for (const name of catalogues) {
    problems.push(...messageProblems(`messages/${name}`, readText(join(messagesDir, name))))
  }
  if (files === 0) problems.push('src: no source files found (an empty scan never passes)')
  if (catalogues.length === 0) problems.push('messages: no message catalogues found')
  return { files, messageFiles: catalogues.length, problems }
}
