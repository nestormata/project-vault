import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/svelte'
import type { Component } from 'svelte'
import { afterEach, beforeAll, beforeEach, describe, expect, it, vi } from 'vitest'
import { ApiClientError } from '$lib/api/client.js'
import { credentialPointExtras } from '$lib/credentials/credential-detail-helpers.js'
import { sampleCredential, sampleProject } from '$lib/test/fixtures.js'

// Story 72.10 (P5): the one-time-password field of the Secret value section. There is no Reveal and
// no "copy without revealing" for a seed (it is write-only); the row can only show the current code
// generated by the server, which hides when its period ends or when the tab hides.

const revealMock = vi.hoisted(() => vi.fn())
const totpMock = vi.hoisted(() => vi.fn())
const addVersionMock = vi.hoisted(() => vi.fn())
vi.mock('$app/state', () => ({
  page: {
    route: { id: '/(app)/projects/[projectId]/credentials/[credentialId]' },
    params: {},
  },
}))
vi.mock('$app/navigation', () => ({
  beforeNavigate: vi.fn(),
  invalidateAll: vi.fn(async () => undefined),
}))
vi.mock('$lib/api/credentials.js', async () => {
  const actual =
    await vi.importActual<typeof import('$lib/api/credentials.js')>('$lib/api/credentials.js')
  return {
    parseRevealedFields: actual.parseRevealedFields,
    isFieldsValue: actual.isFieldsValue,
    revealCredentialValue: revealMock,
    generateCredentialTotp: totpMock,
    addCredentialVersion: addVersionMock,
  }
})

const POINTS = [
  'credential.detail.value',
  'credential.detail.value-fields',
  'credential.detail.value-single',
  'credential.detail.value-copy-status',
  'credential.detail.value-edit-fields',
  'credential.detail.value-add-version',
] as const
const fills = Object.fromEntries(POINTS.map((point) => [point, [{ marker: `fill:${point}` }]]))

const projectId = 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa'
const credentialId = 'cccccccc-cccc-4ccc-8ccc-cccccccccccc'
const WITH_TOTP = sampleCredential({
  id: credentialId,
  projectId,
  fields: [
    { key: 'username', sensitive: false, template: 'login' },
    { key: 'password', sensitive: true, template: 'login' },
    { key: 'Authenticator', sensitive: true, template: 'login', kind: 'totp' },
    { key: 'recovery', sensitive: true, template: 'login', kind: 'multiline' },
  ],
  visibleFieldValues: { username: 'alice' },
})
const ONLY_TOTP = sampleCredential({
  id: credentialId,
  projectId,
  fields: [{ key: 'value', sensitive: true, kind: 'totp' }],
})

let Section: Component<Record<string, unknown>>
beforeAll(async () => {
  const probe = (await import('$lib/test/injection/Probe.svelte')).default
  for (const point of POINTS) {
    vi.doMock(`virtual:pv-inject/${point}`, () => ({
      default: [{ id: `${point}#0`, order: 0, component: probe }],
    }))
  }
  Section = (await import('./CredentialValueSection.svelte')).default as unknown as typeof Section
}, 60_000)
beforeEach(() => {
  revealMock.mockReset()
  totpMock.mockReset()
  addVersionMock.mockReset()
  Object.assign(navigator, { clipboard: { writeText: vi.fn(async () => undefined) } })
})
afterEach(() => cleanup())

function mount(credential = WITH_TOTP, role: 'member' | 'viewer' = 'member') {
  const base = {
    credential,
    projectId,
    credentialId,
    orgRole: role,
    project: sampleProject({ id: projectId, role }),
  }
  return render(Section, {
    props: { ...base, pointProps: credentialPointExtras(base), data: fills },
  })
}

function setVisibility(state: 'hidden' | 'visible') {
  Object.defineProperty(document, 'visibilityState', { configurable: true, get: () => state })
  document.dispatchEvent(new Event('visibilitychange'))
}

const CODE = '287082'
function codeFor(secondsFromNow: number) {
  return {
    field: 'Authenticator',
    code: CODE,
    digits: 6,
    periodSeconds: 30,
    expiresAt: new Date(Date.now() + secondsFromNow * 1000).toISOString(),
    secondsRemaining: secondsFromNow,
    versionNumber: 1,
    retrievedAt: new Date().toISOString(),
  }
}

describe('one-time-password field (72-10)', () => {
  afterEach(() => {
    vi.useRealTimers()
    setVisibility('visible')
  })

  it('offers only "Show code" for the totp row: no Reveal, no copy-without-reveal', () => {
    mount()
    const row = screen.getByTestId('field-row-Authenticator')
    expect(row.textContent).toContain('Authenticator')
    expect(screen.getByRole('button', { name: /show code for authenticator/i })).toBeTruthy()
    expect(row.querySelectorAll('button')).toHaveLength(1)
    // The ordinary sensitive row still has Reveal and copy.
    const password = screen.getByTestId('field-row-password')
    expect(password.querySelectorAll('button')).toHaveLength(2)
  })

  it('labels the main field of the template and nothing else', () => {
    mount()
    expect(screen.getByTestId('field-row-password').textContent).toContain('Main')
    expect(screen.getByTestId('field-row-username').textContent).not.toContain('Main')
  })

  it('shows the server-generated code with a countdown and never calls the reveal route', async () => {
    totpMock.mockResolvedValueOnce(codeFor(20))
    mount()
    await fireEvent.click(screen.getByRole('button', { name: /show code for authenticator/i }))
    await waitFor(() => expect(screen.getByTestId('field-totp-code-Authenticator')).toBeTruthy())
    expect(screen.getByTestId('field-totp-code-Authenticator').textContent).toBe(CODE)
    expect(totpMock).toHaveBeenCalledWith(
      expect.anything(),
      projectId,
      credentialId,
      'Authenticator'
    )
    expect(revealMock).not.toHaveBeenCalled()
    expect(screen.getByRole('status').textContent).toMatch(/Expires in \d+ s/)
  })

  it('removes the code when its period ends', async () => {
    vi.useFakeTimers({ shouldAdvanceTime: false })
    totpMock.mockResolvedValueOnce(codeFor(5))
    mount()
    await fireEvent.click(screen.getByRole('button', { name: /show code for authenticator/i }))
    await vi.advanceTimersByTimeAsync(0)
    expect(screen.queryByTestId('field-totp-code-Authenticator')).not.toBeNull()
    await vi.advanceTimersByTimeAsync(5_100)
    expect(screen.queryByTestId('field-totp-code-Authenticator')).toBeNull()
  })

  it('hides the code when the tab is hidden', async () => {
    totpMock.mockResolvedValueOnce(codeFor(25))
    mount()
    await fireEvent.click(screen.getByRole('button', { name: /show code for authenticator/i }))
    await waitFor(() => expect(screen.getByTestId('field-totp-code-Authenticator')).toBeTruthy())
    setVisibility('hidden')
    await waitFor(() => expect(screen.queryByTestId('field-totp-code-Authenticator')).toBeNull())
  })

  it('copies the code that is on screen, with no extra server call', async () => {
    totpMock.mockResolvedValueOnce(codeFor(25))
    mount()
    await fireEvent.click(screen.getByRole('button', { name: /show code for authenticator/i }))
    await waitFor(() => expect(screen.getByTestId('field-totp-code-Authenticator')).toBeTruthy())
    await fireEvent.click(screen.getByRole('button', { name: /copy code for authenticator/i }))
    expect(navigator.clipboard.writeText).toHaveBeenCalledWith(CODE)
    expect(totpMock).toHaveBeenCalledTimes(1)
  })

  it('shows a calm message when the server refuses, and when the seed is missing', async () => {
    totpMock.mockRejectedValueOnce(
      new ApiClientError(429, { code: 'rate_limited' }, 'Too many requests')
    )
    mount()
    await fireEvent.click(screen.getByRole('button', { name: /show code for authenticator/i }))
    await waitFor(() => expect(screen.getByRole('alert').textContent).toContain('Could not'))

    cleanup()
    totpMock.mockReset()
    totpMock.mockRejectedValueOnce(
      new ApiClientError(422, { code: 'totp_seed_unavailable' }, 'seed missing')
    )
    mount()
    await fireEvent.click(screen.getByRole('button', { name: /show code for authenticator/i }))
    await waitFor(() => expect(screen.getByRole('alert').textContent).toContain('enter the seed'))
  })

  it('shows no code control to a viewer', () => {
    mount(WITH_TOTP, 'viewer')
    expect(screen.queryByRole('button', { name: /show code/i })).toBeNull()
  })

  it('treats a secret that holds only a totp field as a field list', () => {
    mount(ONLY_TOTP)
    expect(screen.getByTestId('field-list')).toBeTruthy()
    expect(screen.getByTestId('field-row-value')).toBeTruthy()
  })

  it('does not load the seed into the editor and keeps it when the field is left empty', async () => {
    revealMock.mockResolvedValueOnce({
      fields: [
        { key: 'username', value: 'alice', sensitive: false },
        { key: 'password', value: 'pw', sensitive: true },
        { key: 'recovery', value: 'a\nb', sensitive: true, kind: 'multiline' },
      ],
      schemaVersion: 2,
      versionNumber: 1,
      retrievedAt: new Date().toISOString(),
    })
    addVersionMock.mockResolvedValueOnce({ credentialId, versionNumber: 2, createdAt: '' })
    mount()
    await fireEvent.click(screen.getByRole('button', { name: /edit fields/i }))
    await waitFor(() => expect(screen.getByRole('button', { name: /save fields/i })).toBeTruthy())
    await fireEvent.click(screen.getByRole('button', { name: /save fields/i }))
    await waitFor(() => expect(addVersionMock).toHaveBeenCalled())
    const body = addVersionMock.mock.calls[0]?.[3] as { fields: Array<Record<string, unknown>> }
    expect(body.fields.find((entry) => entry['kind'] === 'totp')).toEqual({
      key: 'Authenticator',
      value: '',
      sensitive: true,
      kind: 'totp',
    })
    expect(body.fields.find((entry) => entry['key'] === 'recovery')).toMatchObject({
      kind: 'multiline',
    })
  })
})
